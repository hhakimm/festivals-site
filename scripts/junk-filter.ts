/**
 * 비관광 업소 판별 — TourAPI 관광지(contentTypeId=12)에 가끔 섞여 들어오는
 * 병원·의원·약국 등 상업 의료업소 + 정부 연구기관 등을 제거하기 위한 공유 필터.
 *
 * ⚠ 보존 원칙:
 *   - 근대문화유산(예: "부산 구 백제병원", "구 러시아공사관")은 무조건 보존.
 *   - 연구소/진흥원이라도 체험·생태·문화 등 관광 마커가 있으면 보존
 *     (예: "예천 곤충생태원", "한국전통주연구소", "한국국학진흥원", "한우연구소").
 */

// 문화유산성 명소 마커 — 이게 있으면 다른 키워드가 있어도 관광지로 보존
const HERITAGE_RE =
  /(구\s|옛\s|근대|문화재|사적|유적|등록문화|국가유산|기념관|박물관|전시관|역사관|폐교|폐역)/;

// 관광·체험성 마커 — 연구소/진흥원 등 기관 키워드가 있어도 이게 있으면 보존.
// (주의: 아래 INSTITUTION 정크 이름에 등장하는 단어는 넣지 말 것 — 에너지/산림/과학/디자인 등)
const TOURISM_MARKER_RE =
  /(생태|체험|문화|전통|식물|곤충|수목|공원|정원|요리|박물|전시|관광|과학원|국학|탐방|동물|숲|테마|마을|민속|휴양|온천|해수욕|해변)/;

// 상업 의료 업소 패턴 — 진료과목·의원/병원/약국 등. 미앵커(어디에 있어도 매칭).
const MEDICAL_RE =
  /(성형외과|피부과|치과|한의원|한방병원|요양병원|요양원|정형외과|이비인후과|비뇨기과|비뇨의학|산부인과|정신건강의학|정신과의원|마취통증의학|재활의학과|신경외과|흉부외과|신경과의원|안과의원|내과의원|가정의학과|영상의학과|진단검사의학|동물병원|의료원|보건소|보건지소|보건진료|약국|메디컬|클리닉|의원|병원)/;

// 비관광 기관 패턴 — 정부·과학 연구기관, 지하철 차량기지 등.
// 관광 마커(TOURISM_MARKER_RE)가 함께 있으면 보존되므로 체험형 연구소는 안전.
const INSTITUTION_RE = /(연구원|연구소|진흥원|차량사업소|교통공사)/;

/** 비관광 업소·기관이면 true (목록에서 제외 대상). */
export function isNonTourist(title: string): boolean {
  const t = (title || '').trim();
  if (!t) return false;
  if (HERITAGE_RE.test(t)) return false; // 문화유산 → 보존
  if (MEDICAL_RE.test(t)) return true; // 병의원 → 제외
  if (INSTITUTION_RE.test(t) && !TOURISM_MARKER_RE.test(t)) return true; // 기관(관광마커 없음) → 제외
  return false;
}
