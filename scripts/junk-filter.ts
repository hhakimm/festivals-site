/**
 * 비관광 업소 판별 — TourAPI 관광지(contentTypeId=12)에 가끔 섞여 들어오는
 * 병원·의원·약국 등 상업 의료업소를 제거하기 위한 공유 필터.
 *
 * ⚠ 단, 근대문화유산(예: "부산 구 백제병원")은 보존해야 하므로
 *    문화유산 마커가 있으면 무조건 관광지로 간주(걸러내지 않음).
 */

// 문화유산성 명소 마커 — 이게 있으면 의료 키워드가 있어도 관광지로 보존
const HERITAGE_RE =
  /(구\s|옛\s|근대|문화재|사적|유적|등록문화|국가유산|기념관|박물관|전시관|역사관|폐교|폐역)/;

// 상업 의료/비관광 업소 패턴 (특정 진료과목 + 의원/병원 접미사)
const MEDICAL_RE =
  /(성형외과|피부과|치과의원|치과병원|한의원|한방병원|요양병원|요양원|정형외과|이비인후과|비뇨기과|비뇨의학|산부인과|정신건강의학|마취통증의학|재활의학과|신경외과|흉부외과|동물병원|약국|메디컬|클리닉|의원$|병원$)/;

/** 비관광 업소면 true (목록에서 제외 대상). */
export function isNonTourist(title: string): boolean {
  const t = (title || '').trim();
  if (!t) return false;
  if (HERITAGE_RE.test(t)) return false; // 문화유산 → 보존
  return MEDICAL_RE.test(t);
}
